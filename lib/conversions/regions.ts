import type { Zone } from '@/lib/zones/types';

export type Region = 'Americas' | 'Europe' | 'Africa' | 'Asia' | 'Oceania' | 'Global';

export const REGIONS: readonly Region[] = [
  'Americas',
  'Europe',
  'Africa',
  'Asia',
  'Oceania',
] as const;

const ZONE_REGION_MAP: Record<Zone['region'], Region> = {
  'North America': 'Americas',
  'South America': 'Americas',
  Europe: 'Europe',
  Africa: 'Africa',
  Asia: 'Asia',
  'Middle East': 'Asia',
  Oceania: 'Oceania',
  Global: 'Global',
};

export function regionForZone(zone: Pick<Zone, 'region'>): Region {
  return ZONE_REGION_MAP[zone.region];
}

