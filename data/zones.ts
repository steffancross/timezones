/** Lookup by id slug. Throws if not found — call only with known slugs. */
export function getZoneById(id: string): Zone {
  const z = zones.find((z) => z.id === id);
  if (!z) throw new Error(`Unknown zone id: ${id}`);
  return z;
}

/** Lookup by IANA. Returns null if no match. */
export function getZoneByIana(iana: string): Zone | null {
  return zones.find((z) => z.iana === iana) ?? null;
}
